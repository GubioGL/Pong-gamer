def tex_escape(s):
    return str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def write(name, body):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(HEADER + body + "\n")
    print("wrote", (OUT / name).relative_to(_ROOT))


def sci(x):
    if isinstance(x, float) and x != 0 and (abs(x) < 0.1 or abs(x) >= 1e4):
        m, e = f"{x:.0e}".split("e")
        return f"${m}\\times10^{{{int(e)}}}$" if m != "1" else f"$10^{{{int(e)}}}$"
    if isinstance(x, int) and x >= 10_000:
        return f"${x:,}$".replace(",", "\\,")
    return f"{x}"


# ------------------------------------------------------------------ computer
def table_machine():
    m = json.loads((DATA / "custo" / "maquina.json").read_text())
    rows = [("CPU", m["cpu"]), ("logical cores", m["logical_cores"]), ("RAM", f"{m['ram_gb']} GB"),
            ("GPU", "none (all simulations on CPU)"), ("operating system", f"{m['os']} ({m['kernel']})"),
            ("Python", m["python"])]
    rows += [(p, v) for p, v in m["packages"].items() if v]
    body = "\\begin{tabular}{ll}\n\\toprule\n" + "".join(
        f"{tex_escape(k)} & {tex_escape(v)} \\\\\n" for k, v in rows) + "\\bottomrule\n\\end{tabular}"
    write("tab_maquina.tex", body)


