def _pair(pong, snake):
    """'x' when equal in both games, else 'x / y' (Pong / Snake)."""
    return f"{pong}" if pong == snake else f"{pong} / {snake}"


def table_models():
    lines = ["\\small", "\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{L{1.9cm}L{4.1cm}L{1.9cm}L{3.3cm}L{1.6cm}rr}", "\\toprule",
             "agent & architecture & register & initialization & learning rate & \\multicolumn{2}{c}{parameters} \\\\",
             " & & (Pong / Snake) & & & Pong & Snake \\\\", "\\midrule"]
    for a in AGENTS:
        mp, ms = make_agent(a, "pong"), make_agent(a, "snake")
        cp, cs = mp.config, ms.config
        n_p = count_parameters(mp.init(jax.random.PRNGKey(0)))
        n_s = count_parameters(ms.init(jax.random.PRNGKey(0)))
        name, arch, reg, init, lr = DESCR[a]
        fill = {"layers": cp.get("layers", LAYERS), "cutoff": cp.get("cutoff", CUTOFF),
                "hidden": _pair(*("$\\times$".join(map(str, c["hidden"])) for c in (cp, cs))) if "hidden" in cp else "",
                "n_qubits": _pair(cp.get("n_qubits"), cs.get("n_qubits")),
                "n_modes": _pair(cp.get("n_modes"), cs.get("n_modes"))}
        lines.append(f"{name} & {arch.format(**fill)} & {reg.format(**fill)} & {init} & {lr} & {n_p} & {n_s} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write("tab_modelos.tex", "\n".join(lines))


# ------------------------------------------------------------------ DQN
def table_dqn():
    c = GAMES["pong"]["dqn"]
    assert c == GAMES["snake"]["dqn"], "the two games use different DQN settings: update the table"
    rows = [("algorithm", "Double DQN, Huber loss, Adam" if c.double_dqn else "DQN, Huber loss, Adam"),
            ("environment steps per run", sci(c.total_steps)), ("discount $\\gamma$", c.gamma),
            ("learning rate (circuit / MLP)", sci(c.lr)), ("learning rate of $w,b$ (quantum output)", sci(c.lr_out)),
            ("mini-batch", c.batch_size), ("replay buffer", sci(c.buffer_size)),
            ("warm-up (random actions)", f"{c.warmup} steps"), ("gradient step", f"every {c.train_every} environment step(s)"),
            ("target network update", f"every {c.target_update} gradient steps"),
            ("$\\varepsilon$-greedy", f"{c.eps_start} $\\to$ {c.eps_end}, linear over {sci(c.eps_decay_steps)} steps"),
            ("gradient clipping", f"global norm {c.grad_clip}"),
            ("quantum layers $L$", LAYERS), ("Fock cutoff (CV QNN)", f"{CUTOFF} per mode")]
    body = "\\begin{tabular}{ll}\n\\toprule\n" + "".join(f"{a} & {b} \\\\\n" for a, b in rows) + "\\bottomrule\n\\end{tabular}"
    write("tab_dqn.tex", body)


# ------------------------------------------------------------------ reference policies
def reference_scores(n=30):
    rows = []
    for game, policy in [("pong", follow_ball_policy), ("snake", greedy_policy)]:
        for name, pol in [("rule-based", policy), ("random", None)]:
            rng = random.Random(0)
            act = pol or (lambda o, g=game: rng.randrange(3 if g == "pong" else 4))
            returns, scores = [], []
            for s in range(n):
                env = GAMES[game]["env"](10_000 + s)
                obs, done, total = env.reset(), False, 0.0
                while not done:
                    obs, r, done, info = env.step(act(obs))
                    total += r
                returns.append(total)
                scores.append(env.score_player if game == "pong" else env.score)
            rows.append({"game": game, "policy": name, "episodes": n,
                         "mean_return": round(statistics.mean(returns), 3), "sd_return": round(statistics.stdev(returns), 3),
                         "mean_score": round(statistics.mean(scores), 2)})
    out = DATA / "referencia" / "baselines.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    body = ("\\begin{tabular}{llrr}\n\\toprule\ngame & policy & return (mean $\\pm$ sd) & points / food \\\\\n\\midrule\n"
            + "".join(f"{r['game'].capitalize()} & {r['policy']} & ${r['mean_return']:.2f}\\pm{r['sd_return']:.2f}$ & "
                      f"{r['mean_score']:.1f} \\\\\n" for r in rows) + "\\bottomrule\n\\end{tabular}")
    write("tab_referencia.tex", body)
    return rows


